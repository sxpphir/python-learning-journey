# Integer

my_integer_var = 25
print(type(my_integer_var))

# Float

my_float_var = 2.50
print(type(my_float_var))

# String

my_string_var = 'Sapphire'
print(type(my_string_var))

# Boolean

my_boolean_var = False
print(type(my_boolean_var))

# Set

my_set_var = {7, 'Vainilla', 3.14}
print(type(my_set_var))

# Dictionary

my_dictionary_var = {'dessert': 'cake', 'flavour': 'vainilla'}
print(type(my_dictionary_var))

# Tuple

my_tuple_var = (1, 'Hello', 2.7)
print(type(my_tuple_var))

# Range

my_range_var = range(6)
print(type(my_range_var))

# List

my_list_var = [100, 'Jaguar', 3.1416, True]
print(type(my_list_var))

# None

my_none_var = None 
print(type(my_none_var))